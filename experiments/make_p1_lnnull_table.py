"""Paper 1's layer-norm null-direction table, every arm with saved fitted directions.

    python experiments/make_p1_lnnull_table.py     # writes paper1/tables/tab_lnnull.tex

Reads results/ln_null_analysis.json (15 arms), results/round3_fixes.json (the 1.4B arm) and, once
it exists, results/b14r_landing.json (the primary replicate). Generated, so that no arm can be
left out by hand again (strict review, 11 Oct).
"""
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
LABEL = {  # ln_null arm name -> table label, group
    "Pythia-160m L6 (B-2c)": ("Pythia-160m L6", "pooled"),
    "GPT-Neo-125m L10 (B-8b)": ("GPT-Neo-125m L10", "pooled"),
    "GPT-2 L6 re-fit, fit seed 1 (B-15a)": ("GPT-2 L6 re-fit, fit seed", "re-fit"),
    "GPT-2 L6 re-fit, corpus seed 1 (B-15b)": ("GPT-2 L6 re-fit, token sample", "re-fit"),
    "GPT-2 L6 re-fit, sequence split (B-15c)": ("GPT-2 L6 re-fit, sequence split", "re-fit"),
    "GPT-Neo-125m L10, new units (X-1a)": ("GPT-Neo-125m L10, new units", "new units"),
    "GPT-Neo-125m L10, new units, disjoint docs (X-1b)": ("GPT-Neo-125m L10, new units, disjoint documents", "new units"),
    "Pythia-160m L6, float32 (B-2d)": ("Pythia-160m L6, float32", "other"),
    "GPT-Neo-125m L6 (B-17)": ("GPT-Neo-125m L6", "other"),
    "GPT-Neo-125m L6, coordinate dropped (B-17b)": ("GPT-Neo-125m L6, coordinate dropped", "other"),
    "GPT-2 L3 (B-17c)": ("GPT-2 L3", "other"),
    "GPT-2 L3, coordinate dropped (B-17d)": ("GPT-2 L3, coordinate dropped", "other"),
    "GPT-2 L6, noise SNR 1-19 (N-1a)": ("GPT-2 L6, noise SNR 1--19", "noise"),
    "GPT-2 L6, noise SNR 19 (N-1b)": ("GPT-2 L6, noise SNR 19", "noise"),
    "GPT-2 L6, noise SNR 4 (N-1c)": ("GPT-2 L6, noise SNR 4", "noise"),
}


def num(x):
    return "---" if x is None else ("$-$" if x < 0 else "$+$") + f"{abs(x):.3f}"


def row(label, n, a, b):
    pa, pb = a.get("comparison") or a.get("primary_comparison"), b.get("comparison") or b.get("primary_comparison")
    ci = f"[{num(pb['boot_ci95'][0])}, {num(pb['boot_ci95'][1])}]" if pb else "---"
    return (f"{label} & {n} & {a['failures']} $\\to$ {b['failures']} & {a['converged_wrong']} $\\to$ "
            f"{b['converged_wrong']} & {num(pa and pa['diff'])} & {num(pb and pb['diff'])} & {ci} \\\\")


def main():
    ln = json.load(open(ROOT / "results/ln_null_analysis.json"))
    r3 = json.load(open(ROOT / "results/round3_fixes.json"))
    lines = []
    land = ROOT / "results/b14r_landing.json"
    if land.exists():
        arm = json.load(open(land)).get("rerun_as_an_arm")
        if arm:
            lines.append(row("GPT-2 L6, primary replicate", arm["units"], arm["as filed"], arm["identifiable"]))
    for name, (label, grp) in LABEL.items():
        v = ln[name]
        if grp == "pooled" and name.startswith("Pythia"):
            lines.append(row(label + " (pooled)", v["units"], v["as filed"], v["identifiable"]))
        elif grp == "pooled":
            lines.append(row(label + " (pooled)", v["units"], v["as filed"], v["identifiable"]))
            b3 = r3["B3 1.4B arm on the identifiable label"]
            lines.append(row("Pythia-1.4B L12 (pooled)", b3["units"], b3["as filed"], b3["identifiable"]))
        else:
            lines.append(row(label, v["units"], v["as filed"], v["identifiable"]))
    body = ("\\begin{tabular}{lrcccccc}\n\\toprule\narm & $n$ & failures & converged-wrong & $\\Delta$ as filed & "
            "$\\Delta$ identifiable & bootstrap 95\\% CI \\\\\n\\midrule\n" + "\n".join(lines) +
            "\n\\bottomrule\n\\end{tabular}\n")
    out = ROOT / "paper1/tables/tab_lnnull.tex"
    out.parent.mkdir(exist_ok=True)
    out.write_text("% Generated by experiments/make_p1_lnnull_table.py; do not edit by hand.\n" + body, encoding="utf-8")
    print(f"{len(lines)} rows")


if __name__ == "__main__":
    main()
