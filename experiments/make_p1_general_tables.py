"""Paper 1 tables for the standardisation failure across families, estimators and probes, and the
weights-only layer map.

    python experiments/make_p1_general_tables.py
    # writes paper1/tables/tab_general.tex, tab_probe.tex, tab_map.tex
"""
import json
from pathlib import Path

import numpy as np

ROOT = Path(__file__).resolve().parents[1]
OUT = ROOT / "paper1/tables"


def load(p):
    return json.load(open(ROOT / p, encoding="utf-8"))


def agreement(stem, key):
    return float(np.median([json.loads(l)[key] for l in open(ROOT / f"{stem}.jsonl", encoding="utf-8") if l.strip()]))


def general():
    rep, b17, f3, e2b = (load(p) for p in ("results/repair_table.json", "results/b17b_analysis.json",
                                            "results/f3a_analysis.json", "results/e2b_analysis.json"))
    rows = [  # model & layer, method, repair-table key, fits on the coordinate, median |cos|, agreement
        ("GPT-Neo-125m L6", "least squares", "GPT-Neo L6 (B-17)", b17["B-17 GPT-Neo L6, as run"]["fits_with_share_gt_0.5"],
         b17["B-17 GPT-Neo L6, as run"]["median_alignment"], agreement("results/b17_gptneo125m_l6", "stability")),
        ("GPT-2 L3", "least squares", "GPT-2 L3 (B-17c)", b17["B-17c GPT-2 L3, as usual"]["fits_with_share_gt_0.5"],
         b17["B-17c GPT-2 L3, as usual"]["median_alignment"], agreement("results/b17c_gpt2_l3", "stability")),
        ("OPT-125m L5", "least squares", "OPT-125m L5 (F-3a)", f3["L5, as usual"]["fits_with_share_gt_0.5"],
         f3["L5, as usual"]["median_alignment"], f3["L5, as usual"]["median_restart_agreement_all"]),
        ("OPT-125m L3", "least squares", "OPT-125m L3 (F-3a)", f3["L3, as usual"]["fits_with_share_gt_0.5"],
         f3["L3, as usual"]["median_alignment"], f3["L3, as usual"]["median_restart_agreement_all"]),
        ("GPT-Neo-125m L6", "MID", "GPT-Neo L6 (E-2b)", e2b["GPT-Neo L6"]["fits_with_share_gt_0.5"],
         e2b["GPT-Neo L6"]["median_alignment"], e2b["GPT-Neo L6"]["median_restart_agreement_all"]),
        ("GPT-2 L3", "MID", "GPT-2 L3 (E-2b)", e2b["GPT-2 L3"]["fits_with_share_gt_0.5"],
         e2b["GPT-2 L3"]["median_alignment"], e2b["GPT-2 L3"]["median_restart_agreement_all"]),
    ]
    L = ["% Generated by experiments/make_p1_general_tables.py; do not edit by hand.",
         r"\begin{tabular}{llrrccc}", r"\toprule",
         r"model, layer & estimator & fits & on the coordinate & median $|\cos|$ & restart agreement & passes: as fitted $\to$ zeroed \\",
         r"\midrule"]
    for model, est, key, on, med, agr in rows:
        r = rep[key]
        L.append(f"{model} & {est} & {r['units']} & {on} & {med:.3f} & {agr:.3f} & {r['as_fitted']} $\\to$ {r['zeroed']} \\\\")
    L += [r"\bottomrule", r"\end{tabular}"]
    (OUT / "tab_general.tex").write_text("\n".join(L) + "\n", encoding="utf-8")


def probe():
    L = ["% Generated by experiments/make_p1_general_tables.py; do not edit by hand.",
         r"\begin{tabular}{llccccc}", r"\toprule",
         r"model, layer & coordinate & share & accuracy (unscaled) & fold agreement & $|\cos|$ to unscaled & $|\cos|$ to mean difference \\",
         r"\midrule"]
    short = {"EleutherAI/gpt-neo-125M": "GPT-Neo-125m", "gpt2": "GPT-2", "facebook/opt-125m": "OPT-125m",
             "meta-llama/Llama-3.2-1B-Instruct": "Llama-3.2-1B", "google/gemma-3-270m": "Gemma-3-270m"}
    kind = {True: "near-constant", False: "control"}
    for path in ("results/e3_probe.json", "results/e3b_probe.json"):
        for r in load(path)["layers"].values():
            k = r["flagged"] if isinstance(r["flagged"], str) else kind[r["flagged"]]
            L.append(f"{short[r['model']]} L{r['layer']} & {k} & {r['share_std']:.3f} & {r['acc_std']:.4f} ({r['acc_raw']:.4f}) & "
                     f"{r['cv_agreement_std']:.3f} & {r['cos_std_raw']:.3f} & {r['cos_std_diffmean']:.3f} \\\\")
        L.append(r"\midrule")
    L[-1] = r"\bottomrule"
    L.append(r"\end{tabular}")
    (OUT / "tab_probe.tex").write_text("\n".join(L) + "\n", encoding="utf-8")


def layer_map():
    m = load("results/layer_map_weights.json")["models"]
    val = load("results/layer_map_validation.json")
    ln = ("gpt2", "EleutherAI/gpt-neo", "EleutherAI/pythia", "facebook/opt")
    L = ["% Generated by experiments/make_p1_general_tables.py; do not edit by hand.",
         r"\begin{tabular}{llrl}", r"\toprule", r"model & norm & flagged / layers & checked against activations \\", r"\midrule"]
    vkey = {"gpt2": "gpt2", "EleutherAI/gpt-neo-125M": "EleutherAI/gpt-neo-125M", "google/gemma-3-270m": "google/gemma-3-270m",
            "meta-llama/Llama-3.2-1B": "meta-llama/Llama-3.2-1B-Instruct"}
    for name, r in m.items():
        norm = "LayerNorm" if name.startswith(ln) else "RMSNorm"
        if "candidates" in r:
            chk = ""
            if name in vkey:
                v = val[vkey[name]]
                chk = "agrees on every layer" + (" (instruct model)" if "Instruct" in vkey[name] else "") if v["agree"] else "disagrees"
            L.append(f"\\texttt{{{name}}} & {norm} & {len(r['candidates'])} / {r['layers']} & {chk} \\\\")
        elif "not_applicable" in r:
            L.append(f"\\texttt{{{name}}} & post-norm & --- & not applicable \\\\")
        else:
            L.append(f"\\texttt{{{name}}} & {norm} & --- & no safetensors; OPT-125m mapped from activations (2 / 12) \\\\"
                     if name == "facebook/opt-125m" else f"\\texttt{{{name}}} & {norm} & --- & no safetensors \\\\")
    L += [r"\bottomrule", r"\end{tabular}"]
    (OUT / "tab_map.tex").write_text("\n".join(L) + "\n", encoding="utf-8")


if __name__ == "__main__":
    general()
    probe()
    layer_map()
    print("wrote tab_general.tex, tab_probe.tex, tab_map.tex")
