    body = "\n".join(" & ".join(r) + " \\\\" for r in rows)
    write("tab_predictions", "\\begin{tabular}{llll}\n\\toprule\nrun (filed) & filed prediction & observed & outcome \\\\\n"
          "\\midrule\n" + body + "\n\\bottomrule\n\\end{tabular}\n")


