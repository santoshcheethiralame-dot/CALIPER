def tex_escape(s):
    rep = {"\\": "\\textbackslash{}", "{": "\\{", "}": "\\}", "_": "\\_", "%": "\\%", "&": "\\&", "#": "\\#", "$": "\\$"}
    return "".join(rep.get(ch, ch) for ch in s)


